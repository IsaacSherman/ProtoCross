using System.Text;
using ProtoCross.Backend;

namespace ProtoCross.Backend.CSharp;

/// <summary>
/// The MSBuild project that builds and runs generated C# ProtoCross tests.
/// </summary>
/// <remarks>
/// <para>
/// This exists because <c>--test-out</c> on its own produces source that nothing can build. The
/// repository's own harness knows the answer, but as <c>internal</c> code in the test assembly, so
/// every consumer was left to rediscover it from prose.
/// </para>
/// <para>
/// It is deliberately not a copy of that harness project. <c>CSharpTestWorkspace</c> is tuned for a
/// hostile offline sandbox -- it clears every NuGet source, treats warnings as errors, forces
/// checked arithmetic, and stubs out <c>Directory.Build.props</c> so nothing above it applies. Each
/// of those is right for proving the compiler's output survives a hostile project and wrong for a
/// project a user drops into their own repository, so none of them are emitted here.
/// </para>
/// </remarks>
public static class CSharpTestProject
{
    /// <summary>The project's name where nothing chose one (spec 25.3.2).</summary>
    public const string DefaultProjectName = "ProtoCrossTests";

    /// <summary>The framework the project targets where nothing chose one (spec 25.3.2).</summary>
    public const string DefaultTargetFramework = "net10.0";

    /// <summary>The project file's name where nothing chose one.</summary>
    public const string FileName = DefaultProjectName + ".csproj";

    /// <summary>The project file's name, which is the project's.</summary>
    public static string FileNameFor(ScaffoldSettings settings)
        => (settings.CSharpProjectName ?? DefaultProjectName) + ".csproj";

    /// <summary>
    /// Package versions the emitted project pins.
    /// </summary>
    /// <remarks>
    /// A consumer has no <c>Directory.Packages.props</c> of ours, so unlike the harness project
    /// these cannot be left to central package management and must be stated. That makes them a
    /// second copy of versions this repository already declares, so
    /// <c>ScaffoldTests.EveryPinnedVersionMatchesCentralPackageManagement</c> fails if the two ever
    /// disagree.
    /// </remarks>
    public static IReadOnlyDictionary<string, string> PackageVersions { get; } =
        new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["Google.Protobuf"] = "3.31.1",
            ["Grpc.Tools"] = "2.80.0",
            ["Microsoft.NET.Test.Sdk"] = "17.14.1",
            ["xunit.v3"] = "3.2.2",
            ["xunit.runner.visualstudio"] = "3.1.5",
        };

    public static string Build(ScaffoldOptions options)
    {
        var builder = new StringBuilder();

        builder.AppendLine("<!--");
        builder.AppendLine("    Generated by protocross. Builds and runs ProtoCross tests for this project's");
        builder.AppendLine("    generated C# behavior. Changes to this file will be lost when it is regenerated.");
        builder.AppendLine("-->");
        builder.AppendLine("<Project Sdk=\"Microsoft.NET.Sdk\">");
        builder.AppendLine();
        builder.AppendLine("  <PropertyGroup>");
        builder.AppendLine($"    <TargetFramework>{options.Settings.CSharpTargetFramework ?? DefaultTargetFramework}</TargetFramework>");
        builder.AppendLine("    <Nullable>enable</Nullable>");
        builder.AppendLine("    <ImplicitUsings>enable</ImplicitUsings>");
        builder.AppendLine("    <IsPackable>false</IsPackable>");
        builder.AppendLine("    <!--");
        builder.AppendLine("      A ProtoCross 'expect fail' test asserts that a method terminates the process, which");
        builder.AppendLine("      cannot be observed from inside it. The generated test relaunches this assembly for");
        builder.AppendLine("      one named test and inspects how the child ended, so it has to be executable.");
        builder.AppendLine("    -->");
        builder.AppendLine("    <OutputType>Exe</OutputType>");
        builder.AppendLine("    <!--");
        builder.AppendLine("      The package references below state their own versions, which is an error when a");
        builder.AppendLine("      Directory.Packages.props anywhere above this directory turns central package");
        builder.AppendLine("      management on (NU1008). This project is self-contained, so opt it back out.");
        builder.AppendLine("    -->");
        builder.AppendLine("    <ManagePackageVersionsCentrally>false</ManagePackageVersionsCentrally>");

        if (options.BehaviorFileNames is not null)
        {
            builder.AppendLine("    <!--");
            builder.AppendLine("      Only the files the compiler wrote this time are compiled, each named below. A test");
            builder.AppendLine("      file an earlier build left here, from a source since renamed or dropped, would call");
            builder.AppendLine("      behavior that is no longer built.");
            builder.AppendLine("    -->");
            builder.AppendLine("    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>");
        }

        builder.AppendLine("  </PropertyGroup>");
        builder.AppendLine();
        builder.AppendLine("  <ItemGroup>");

        foreach (var (package, version) in PackageVersions)
        {
            // Grpc.Tools contributes build-time protoc integration and nothing at runtime, so it
            // must not flow to anything referencing this project.
            var attributes = package == "Grpc.Tools"
                ? " PrivateAssets=\"all\" ExcludeAssets=\"runtime\""
                : string.Empty;

            builder.AppendLine(
                $"    <PackageReference Include=\"{package}\" Version=\"{version}\"{attributes} />");
        }

        builder.AppendLine("  </ItemGroup>");
        builder.AppendLine();
        EmitTests(builder, options);
        EmitBehavior(builder, options);
        // A source that extends only well-known types has nothing to generate: those ship
        // precompiled in Google.Protobuf and are filtered out of the schema list. An empty item
        // group builds fine, but a comment promising a protoc run above one would be a lie.
        if (options.ProtoFiles.Count > 0)
        {
            builder.AppendLine("  <!--");
            builder.AppendLine("    Protobuf message classes. Grpc.Tools runs protoc during the build, so there is no");
            builder.AppendLine("    separate protoc step to remember and no generated .cs to keep in sync by hand.");
            builder.AppendLine("  -->");
            builder.AppendLine("  <ItemGroup>");

            foreach (var proto in options.ProtoFiles)
            {
                var include = Escape(Join(proto.ProtoRoot, proto.RelativePath));
                var root = Escape(Normalize(proto.ProtoRoot));
                builder.AppendLine(
                    $"    <Protobuf Include=\"{include}\" ProtoRoot=\"{root}\" GrpcServices=\"None\" />");
            }

            builder.AppendLine("  </ItemGroup>");
            builder.AppendLine();
        }

        builder.AppendLine("</Project>");

        return builder.ToString();
    }

    /// <summary>
    /// The item group that compiles the generated tests, where the build named its files; nothing where
    /// it did not, since the SDK's default items then compile every <c>.cs</c> file beside the project.
    /// </summary>
    /// <remarks>
    /// Named because the behavior is (see <see cref="EmitBehavior"/>). A test file an earlier build left
    /// beside the project, from a source since renamed or dropped, calls behavior this build no longer
    /// writes, so compiling it once the behavior is named stopped the build on a member that does not
    /// exist. It used to build, against the stale behavior the glob also took in, and run as a test no
    /// source declares.
    /// </remarks>
    private static void EmitTests(StringBuilder builder, ScaffoldOptions options)
    {
        if (options.BehaviorFileNames is null)
        {
            return;
        }

        builder.AppendLine("  <!--");
        builder.AppendLine("    The generated tests, beside this project.");
        builder.AppendLine("  -->");
        builder.AppendLine("  <ItemGroup>");

        foreach (var test in options.TestSourceFileNames.Where(IsCSharpSource))
        {
            builder.AppendLine($"    <Compile Include=\"{Escape(EscapeItemSpec(Normalize(test)))}\" />");
        }

        builder.AppendLine("  </ItemGroup>");
        builder.AppendLine();
    }

    /// <summary>The item group that compiles the behavior the generated tests call into.</summary>
    /// <remarks>
    /// <para>
    /// Each file the build wrote is named, rather than every <c>.cs</c> file below the behavior
    /// directory. That directory is also where a consumer keeps protoc's own C# output for their own
    /// build, and this project generates the message classes itself, through Grpc.Tools. A glob took
    /// both in and stopped the build on every member of every message, defined twice, with nothing
    /// in the errors to say why (#234). A behavior file an earlier build left there, from a source
    /// since renamed, is left out for the same reason.
    /// </para>
    /// <para>
    /// A caller that does not say which files the behavior is still gets the glob, and the SDK's
    /// default items for the tests, which is what this project compiled before the names were known.
    /// </para>
    /// </remarks>
    private static void EmitBehavior(StringBuilder builder, ScaffoldOptions options)
    {
        builder.AppendLine("  <!--");
        // No '--' anywhere in an emitted comment: XML forbids it, so naming the compiler flag
        // literally here would produce a project MSBuild refuses to load (MSB4025).
        builder.AppendLine("    The behavior emitted into the compiler's output directory. The generated tests");
        builder.AppendLine("    call into it, so it is compiled here rather than referenced as a separate project.");

        if (options.BehaviorFileNames is not null)
        {
            builder.AppendLine("    Each file is named, so that nothing else kept there, such as protoc's own C#");
            builder.AppendLine("    output, is compiled with it.");
        }

        builder.AppendLine("  -->");
        builder.AppendLine("  <ItemGroup>");

        IEnumerable<string> includes = options.BehaviorFileNames is { } names
            ? names.Where(IsCSharpSource).Select(name => EscapeItemSpec(Join(options.BehaviorDirectory, name)))
            : [Join(options.BehaviorDirectory, "**/*.cs")];

        foreach (var include in includes)
        {
            builder.AppendLine($"    <Compile Include=\"{Escape(include)}\" />");
        }

        builder.AppendLine("  </ItemGroup>");
        builder.AppendLine();
    }

    private static bool IsCSharpSource(string fileName)
        => fileName.EndsWith(".cs", StringComparison.OrdinalIgnoreCase);

    /// <summary>
    /// MSBuild accepts either separator on Windows and only this one elsewhere, so emitted paths use
    /// it regardless of the platform the compiler happened to run on.
    /// </summary>
    private static string Normalize(string path) => path.Replace('\\', '/');

    private static string Join(string directory, string relative)
    {
        var normalized = Normalize(directory);
        return normalized.Length == 0 || normalized == "."
            ? Normalize(relative)
            : normalized.TrimEnd('/') + "/" + Normalize(relative);
    }

    /// <summary>
    /// Escapes the characters MSBuild reads as syntax in an item's path, so a file is one item whatever
    /// its name holds.
    /// </summary>
    /// <remarks>
    /// Only for a path that names one file. A file name may hold a <c>;</c>, which would otherwise
    /// make it two items, or a <c>*</c>, which would make it a pattern. A glob is written to be read
    /// as one, so it is left as it is. The percent sign goes first, since it is what the others
    /// become.
    /// </remarks>
    private static string EscapeItemSpec(string path) => path
        .Replace("%", "%25")
        .Replace(";", "%3B")
        .Replace("$", "%24")
        .Replace("@", "%40")
        .Replace("'", "%27")
        .Replace("*", "%2A")
        .Replace("?", "%3F");

    /// <summary>Escapes the five XML predefined entities, so a path with an ampersand still parses.</summary>
    private static string Escape(string value) => value
        .Replace("&", "&amp;")
        .Replace("<", "&lt;")
        .Replace(">", "&gt;")
        .Replace("\"", "&quot;")
        .Replace("'", "&apos;");
}
