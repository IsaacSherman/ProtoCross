using System.Globalization;
using System.Text;
using ProtoCross.Backend;
using ProtoCross.Diagnostics;
using ProtoCross.Ir;
using ProtoCross.Semantics;
using ProtoCross.Syntax;
using ProtoCross.Types;

namespace ProtoCross.Backend.CSharp;

public sealed partial class CSharpBackend
{
    public IReadOnlyList<GeneratedFile> EmitTests(
        IrModule module,
        BackendOptions options,
        DiagnosticBag diagnostics)
    {
        if (module.Tests.Count == 0)
        {
            return [];
        }

        var sourceName = Path.GetFileNameWithoutExtension(options.SourceFileName);
        var writer = new SourceWriter();
        WriteTestHeader(writer, options);

        // Names are allocated once and reused, because an 'expect fail' test needs the same
        // identifier in three places: the fact, the key it passes to the child process, and the
        // case label the child dispatches on.
        var usedNames = new HashSet<string>(StringComparer.Ordinal);
        var methodNames = module.Tests.ToDictionary(test => test, test => UniqueTestMethodName(test, usedNames));
        var failTests = module.Tests.Where(t => t.Expectation is IrTestFailExpectation).ToList();
        var placement = new Placement(options.ProjectNamespace);

        using (writer.Block("namespace ProtoCross.GeneratedTests"))
        {
            var className = ToIdentifier(sourceName) + "ProtoCrossTests";
            using var classScope = writer.Block($"public sealed class {className}");

            var first = true;
            foreach (var test in module.Tests)
            {
                if (!first)
                {
                    writer.WriteLine();
                }

                first = false;
                EmitTest(writer, test, methodNames[test], sourceName, placement);
            }

            if (failTests.Count > 0)
            {
                writer.WriteLine();
                EmitFailTestDispatcher(writer, failTests, methodNames, sourceName, placement);
            }

            if (module.Tests.Any(test => test.Expectation is IrTestFieldsExpectation))
            {
                writer.WriteLine();
                EmitFieldExpectations(writer);
            }
        }

        var fileName = sourceName + NameConventions.TestsSuffix + ".g.cs";

        // The support file is emitted only when something needs it, so a source with no 'expect
        // fail' test does not gain a file that starts child processes.
        return failTests.Count > 0
            ?
            [
                new GeneratedFile(CSharpTestRuntime.FileName, CSharpTestRuntime.Source),
                new GeneratedFile(fileName, writer.ToString()),
            ]
            : [new GeneratedFile(fileName, writer.ToString())];
    }

    public IReadOnlyList<GeneratedFile> EmitTestProject(
        ScaffoldOptions options,
        DiagnosticBag diagnostics)
        => [new GeneratedFile(CSharpTestProject.FileName, CSharpTestProject.Build(options))];

    private static void WriteTestHeader(SourceWriter writer, BackendOptions options)
    {
        writer.WriteLine("// <auto-generated>");
        writer.WriteLine($"//     Generated by protocross from {options.SourceFileName}.");
        writer.WriteLine("//     ProtoCross unit tests for generated behavior.");
        foreach (var line in options.PolicyDescription)
        {
            writer.WriteLine($"//     {line}");
        }

        writer.WriteLine("//     Changes to this file will be lost when the code is regenerated.");
        writer.WriteLine("// </auto-generated>");
        writer.WriteLine();
        writer.WriteLine("#nullable enable");
        writer.WriteLine();
        writer.WriteLine("// Every expectation is asserted the same way, whatever its type, so that the");
        writer.WriteLine("// emitted assertion follows from the declared 'expect return' rather than from the");
        writer.WriteLine("// backend guessing which overload reads better.");
        writer.WriteLine("#pragma warning disable xUnit2004 // Do not use Assert.Equal for boolean conditions");
        writer.WriteLine();
    }

    private static void EmitTest(
        SourceWriter writer, IrTest test, string methodName, string sourceName, Placement placement)
    {
        // The display name is the backend-independent identity rather than the mangled method name,
        // so a conformance harness reading the test log sees the same string every backend reports.
        writer.WriteLine($"[global::Xunit.Fact(DisplayName = {FormatString(test.Identity)})]");
        using var scope = writer.Block($"public void {methodName}()");

        if (test.Expectation is IrTestFailExpectation)
        {
            EmitFailTest(writer, test, methodName, sourceName);
            return;
        }

        if (test.Target.HasReceiver)
        {
            EmitReceiverCreation(writer, test.Receiver, placement);
        }

        switch (test.Expectation)
        {
            case IrTestReturnExpectation returnExpectation:
                writer.WriteLine(
                    "global::Xunit.Assert.Equal("
                    + $"{Expression(returnExpectation.Value, placement, "receiver")}, {Invocation(test, placement)});");
                break;

            case IrTestFieldsExpectation fields:
                EmitFieldChecks(writer, test, fields, placement);
                break;

            default:
                throw new ArgumentOutOfRangeException(nameof(test), test.Expectation, "Unhandled C# test expectation.");
        }
    }

    /// <summary>
    /// Emits what an expected message literal checks: the call, held in a local, and then each field the
    /// literal sets, in the order <see cref="IrExpectedFields"/> gives (spec 25.3).
    /// </summary>
    /// <remarks>
    /// A field is checked by <c>ExpectSet</c> and <c>ExpectField</c> rather than by <c>Assert.Equal</c>,
    /// so a failure says which field it was: a test checking five fields that reported only two values
    /// would leave the reader to find which.
    /// </remarks>
    private static void EmitFieldChecks(SourceWriter writer, IrTest test, IrTestFieldsExpectation fields, Placement placement)
    {
        var expected = IrExpectedFields.Of(fields);
        writer.WriteLine($"var {Escape(expected.Result.Name)} = {Invocation(test, placement)};");

        foreach (var check in expected.Checks)
        {
            var field = FormatString($"{test.Identity}: '{check.Path}'");
            writer.WriteLine(check switch
            {
                IrPresenceCheck presence
                    => $"ExpectSet({Expression(presence.Presence, placement, "receiver")}, {field});",
                IrValueCheck value
                    => $"ExpectField({Expression(value.Expected, placement, "receiver")}, "
                        + $"{Expression(value.Actual, placement, "receiver")}, {field});",
                _ => throw new ArgumentOutOfRangeException(nameof(fields), check, "Unhandled field check."),
            });
        }
    }

    /// <summary>The two checks an expected message literal's fields are asserted by, written once per test class.</summary>
    /// <remarks>
    /// <para>
    /// A field is equal by <c>EqualityComparer&lt;T&gt;.Default</c>, which is what <c>Assert.Equal</c>
    /// compares an <c>expect return</c> by: a NaN meets a NaN, as it does there (spec 25.3), and two
    /// <c>ByteString</c>s compare by their bytes. Its type is inferred from both arguments, so a literal of
    /// a narrower type than the field widens to it rather than comparing unequal.
    /// </para>
    /// <para>
    /// <c>ExpectSet</c> does not return when the field is unset, and says so with <c>DoesNotReturnIf</c>,
    /// so that the compiler's null-state analysis reads a nested message's fields after it without a
    /// warning. Generated tests build with warnings as errors, and protoc declares a message field as
    /// a reference that may be null.
    /// </para>
    /// <para>
    /// Written only where a test needs them, so every other test file is generated as it always was.
    /// </para>
    /// </remarks>
    private static void EmitFieldExpectations(SourceWriter writer)
    {
        writer.WriteLine("/// <summary>Fails the test unless a field an expected message sets is set.</summary>");
        using (writer.Block(
            "private static void ExpectSet([global::System.Diagnostics.CodeAnalysis.DoesNotReturnIf(false)] bool set, string field)"))
        {
            using (writer.Block("if (!set)"))
            {
                writer.WriteLine("global::Xunit.Assert.Fail($\"{field} is not set\");");
            }
        }

        writer.WriteLine();
        writer.WriteLine("/// <summary>Fails the test unless a field an expected message sets has the value it sets.</summary>");
        using (writer.Block("private static void ExpectField<T>(T expected, T actual, string field)"))
        {
            using (writer.Block("if (!global::System.Collections.Generic.EqualityComparer<T>.Default.Equals(expected, actual))"))
            {
                writer.WriteLine("global::Xunit.Assert.Fail($\"{field}: expected {expected}, actual {actual}\");");
            }
        }
    }

    /// <summary>
    /// Emits an <c>expect fail</c> test. What it asserts is that the call does not return, which no
    /// assertion inside the same process can observe, so the call happens in a child process and
    /// this only inspects how that process ended.
    /// </summary>
    private static void EmitFailTest(SourceWriter writer, IrTest test, string methodName, string sourceName)
    {
        var key = FormatString(sourceName + ":" + methodName);

        writer.WriteLine($"var unexpected = {CSharpTestRuntime.TypeName}.DescribeExpectFail({key});");
        writer.WriteLine("global::Xunit.Assert.True(");
        writer.Indent();
        writer.WriteLine("unexpected is null,");
        writer.WriteLine($"{FormatString(test.Identity + " expected terminal failure, but ")} + unexpected);");
        writer.Unindent();
    }

    /// <summary>
    /// Emits the module initializer a child process lands in. It runs before the test host's entry
    /// point, so a child never starts a normal test run.
    /// </summary>
    private static void EmitFailTestDispatcher(
        SourceWriter writer,
        IReadOnlyList<IrTest> failTests,
        IReadOnlyDictionary<IrTest, string> methodNames,
        string sourceName,
        Placement placement)
    {
        writer.WriteLine("/// <summary>");
        writer.WriteLine("/// Runs the single 'expect fail' test this process was launched for, and returns");
        writer.WriteLine("/// immediately during an ordinary test run.");
        writer.WriteLine("/// </summary>");
        writer.WriteLine("[global::System.Runtime.CompilerServices.ModuleInitializer]");
        using var scope = writer.Block("internal static void RunRequestedProtoCrossFailTest()");

        writer.WriteLine(
            $"var requested = {CSharpTestRuntime.TypeName}.RequestedTest({FormatString(sourceName)});");
        using (writer.Block("if (requested is null)"))
        {
            writer.WriteLine("return;");
        }

        writer.WriteLine();
        writer.WriteLine($"var key = {FormatString(sourceName + ":")} + requested;");
        writer.WriteLine();
        writer.WriteLine("// The parent reads these two markers rather than an exit code: how a host");
        writer.WriteLine("// reports a fail-fast, and how long it takes to, is not something a test can");
        writer.WriteLine("// depend on. The first says the body ran; the second says it came back, which");
        writer.WriteLine("// is exactly the failure an 'expect fail' test is looking for.");
        writer.WriteLine($"global::System.Console.Out.WriteLine({CSharpTestRuntime.TypeName}.StartedMarker + key);");
        writer.WriteLine("global::System.Console.Out.Flush();");
        writer.WriteLine();
        using (writer.Block("switch (requested)"))
        {
            foreach (var test in failTests)
            {
                // Each case gets its own block: the receiver local would otherwise collide with the
                // one declared by the case before it.
                writer.WriteLine($"case {FormatString(methodNames[test])}:");
                writer.WriteLine("{");
                writer.Indent();

                if (test.Target.HasReceiver)
                {
                    EmitReceiverCreation(writer, test.Receiver, placement);
                }

                // The call is expected not to return, so its result is deliberately unused.
                writer.WriteLine(test.Target.ReturnType is VoidType
                    ? $"{Invocation(test, placement)};"
                    : $"_ = {Invocation(test, placement)};");
                writer.WriteLine("break;");

                writer.Unindent();
                writer.WriteLine("}");
                writer.WriteLine();
            }

            writer.WriteLine("default:");
            writer.Indent();
            writer.WriteLine($"global::System.Environment.Exit({CSharpTestRuntime.TypeName}.UnknownTest);");
            writer.WriteLine("break;");
            writer.Unindent();
        }

        writer.WriteLine();
        writer.WriteLine("// Reached only when the method returned instead of terminating the process.");
        writer.WriteLine($"global::System.Console.Out.WriteLine({CSharpTestRuntime.TypeName}.ReturnedMarker + key);");
        writer.WriteLine("global::System.Console.Out.Flush();");
        writer.WriteLine($"global::System.Environment.Exit({CSharpTestRuntime.TypeName}.DidNotTerminate);");
    }

    /// <summary>The call under test, against the local named <c>receiver</c> where it has one.</summary>
    private static string Invocation(IrTest test, Placement placement)
    {
        var arguments = test.Target.HasReceiver ? ["receiver"] : new List<string>();
        arguments.AddRange(test.Arguments.Select(a => Expression(a.Value, placement, "receiver")));

        return $"{placement.QualifiedClassOf(test.Target)}."
            + $"{placement.MethodNameOf(test.Target)}({string.Join(", ", arguments)})";
    }

    /// <summary>Declares the local named <c>receiver</c> that a test calls its method on.</summary>
    /// <remarks>
    /// A fixture's values cannot name a receiver (spec 25.3), so <c>receiver</c> is never read inside
    /// its own initializer.
    /// </remarks>
    private static void EmitReceiverCreation(SourceWriter writer, IrMessageLiteral receiver, Placement placement)
        => writer.WriteLine($"var receiver = {MessageLiteral(receiver, placement, "receiver")};");

    private static string UniqueTestMethodName(IrTest test, HashSet<string> usedNames)
    {
        // A factory's method is named as the test targets it, so its test reads 'Invoice.factory.create'.
        var target = test.Target.HasReceiver
            ? $"{test.Target.Receiver.Name}_{test.Target.Name}"
            : $"{test.Target.Receiver.Name}_{ContextualKeywords.Factory}_{test.Target.Name}";
        var baseName = ToIdentifier($"{target}_{test.Name}");
        var candidate = baseName;
        var suffix = 2;
        while (!usedNames.Add(candidate))
        {
            candidate = baseName + suffix.ToString(CultureInfo.InvariantCulture);
            suffix++;
        }

        return candidate;
    }

    private static string ToIdentifier(string text)
    {
        var builder = new StringBuilder(text.Length);
        var capitalizeNext = true;

        foreach (var c in text)
        {
            if (char.IsLetterOrDigit(c))
            {
                builder.Append(capitalizeNext ? char.ToUpperInvariant(c) : c);
                capitalizeNext = false;
                continue;
            }

            capitalizeNext = true;
        }

        if (builder.Length == 0 || !char.IsLetter(builder[0]))
        {
            builder.Insert(0, 'T');
        }

        var identifier = builder.ToString();
        return ReservedWords.Contains(identifier) ? "@" + identifier : identifier;
    }
}
